use crate::{INPUT_EVENTS, RAW_INPUTS, VALUE_BYTES};
use core::{fmt, num::NonZeroU64};
use moteframe_ble::{
    CheckedNotifier, NotificationBackend, NotificationRef, NotifyError, WriteBufferError, WriteSlot,
};
use moteframe_input::{
    Button, ButtonConfig, ButtonEvent, Direction, EventQueue, InputError, Touch, TouchConfig,
    TouchEvent, TouchSample,
};

/// A complete normalized sample retaining its physical sampling time in microseconds.
#[derive(Clone, Copy)]
pub enum Sample {
    /// Normalized button level and original sampling time.
    Button {
        /// True means pressed.
        pressed: bool,
        /// Monotonic microseconds in one boot epoch.
        at_us: u64,
    },
    /// Normalized contact sample and original sampling time.
    Touch {
        /// No vendor gesture/register codes.
        sample: TouchSample,
        /// Monotonic microseconds.
        at_us: u64,
    },
    /// Advance the touch hold timer, in the same ordered input stream.
    TouchTick(u64),
}
impl fmt::Debug for Sample {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Sample").finish_non_exhaustive()
    }
}
/// Original receive-side error; not an invented successful event.
#[derive(Debug, PartialEq, Eq)]
pub enum ReceiveError<E> {
    /// Adapter failure.
    Backend(E),
    /// Complete value could not enter the caller slot.
    Slot(WriteBufferError),
}
/// Minimal example port around an external BLE stack or an explicit offline model.
pub trait Link: NotificationBackend {
    /// Finite service call; Some only for a live subscribed complete target identity.
    /// The adapter retires its own queued committed values when a connection,
    /// database, bearer or subscription is retired, even between poll calls.
    /// Re-enabled subscriptions need a nonreused identity; old values must never
    /// be relabeled with it. Retiring only this consumer's RX slot is insufficient.
    /// # Errors
    /// Preserve the original adapter failure. No cached route is used on failure.
    fn poll(&mut self) -> Result<Option<Self::Target>, Self::Error>;
    /// Move at most one complete committed write; retain source on slot rejection.
    /// # Errors
    /// Preserve original adapter/slot failure and never truncate.
    fn receive(
        &mut self,
        slot: &mut WriteSlot<Self::Target, VALUE_BYTES>,
    ) -> Result<(), ReceiveError<Self::Error>>;
    /// True only with evidence that this error means no notification was queued.
    fn definitely_not_queued(&self, error: &Self::Error) -> bool;
}
/// Opaque owner-generation plus nonreused sequence, not a wire identifier.
#[derive(Clone, Copy, PartialEq, Eq)]
pub struct TxToken {
    owner: NonZeroU64,
    sequence: u64,
}
impl fmt::Debug for TxToken {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("TxToken(..)")
    }
}
/// Explicit adapter-proven outcome of the same uncertain operation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Resolution {
    /// Backend proves acceptance; do not resubmit.
    Accepted,
    /// Backend proves nonacceptance; allow a later bounded attempt.
    NotAccepted,
}
/// Notification admission state, separate from delivery or peer ACK.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TxState {
    /// No uncertainty prevents a bounded attempt.
    Ready,
    /// Explicit resolution required for this exact token.
    Uncertain(TxToken),
    /// Invalid backend capacity; repair and explicitly retry.
    Faulted(TxToken),
}
/// Local admission failure, before changing the retained value.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum EnqueueError {
    /// Actual queue/slot is full.
    Full,
    /// Entire value exceeds actual storage.
    TooLong,
    /// No currently verified subscribed route.
    NoTarget,
    /// Recovery token is stale or has the wrong state.
    WrongToken,
    /// Token owner cannot allocate another nonreused identity.
    Exhausted,
}
/// Immutable visual state; payload bytes are never interpreted as a protocol.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Snapshot {
    /// Generic selected swatch, 0..3.
    pub selection: u8,
    /// Last RX activity toggle.
    pub rx_active: bool,
    /// Last accepted TX activity toggle.
    pub tx_active: bool,
    /// A subscribed route was observed.
    pub connected: bool,
}
/// Next-frame damage generated by independent service work.
#[derive(Clone, Copy, Debug, Default)]
pub struct Damage {
    /// Full scene, e.g. selection/connection changed.
    pub full: bool,
    /// RX marker only.
    pub rx: bool,
    /// TX marker only.
    pub tx: bool,
}
struct Pending<T: Copy> {
    target: T,
    bytes: [u8; VALUE_BYTES],
    len: usize,
    token: TxToken,
}
/// Per-step original first errors and logical progress. Counters saturate.
#[derive(Debug)]
pub struct ServiceReport<E> {
    /// Service rounds, including pre/post UI.
    pub rounds: u32,
    /// Actual poll calls.
    pub polls: u32,
    /// Accepted complete RX values, including empty values.
    pub received: u32,
    /// Actual notification attempts.
    pub attempts: u32,
    /// Backend queue admissions, never peer ACK.
    pub accepted: u32,
    /// Old pending notifications retired by route change.
    pub retired: u32,
    /// Old target RX values discarded.
    pub stale_rx: u32,
    /// Raw samples successfully handed to input state machines.
    pub samples: u32,
    /// Recognized events consumed.
    pub events: u32,
    /// Invalid input samples explicitly rejected.
    pub rejected: u32,
    /// Original first poll failure.
    pub poll_error: Option<E>,
    /// Original first RX failure.
    pub receive_error: Option<ReceiveError<E>>,
    /// Original first TX failure.
    pub notify_error: Option<NotifyError<E>>,
    /// Original first input failure.
    pub input_error: Option<InputError>,
}
impl<E> Default for ServiceReport<E> {
    fn default() -> Self {
        Self {
            rounds: 0,
            polls: 0,
            received: 0,
            attempts: 0,
            accepted: 0,
            retired: 0,
            stale_rx: 0,
            samples: 0,
            events: 0,
            rejected: 0,
            poll_error: None,
            receive_error: None,
            notify_error: None,
            input_error: None,
        }
    }
}
fn first<T>(slot: &mut Option<T>, error: T) {
    if slot.is_none() {
        *slot = Some(error);
    }
}

/// Example-owned independent lanes; no display, reader or payload Debug bound.
pub struct Services<B: Link> {
    link: B,
    target: Option<B::Target>,
    verified: bool,
    rx: WriteSlot<B::Target, VALUE_BYTES>,
    pending: Option<Pending<B::Target>>,
    tx_state: TxState,
    next_token: u64,
    owner_generation: NonZeroU64,
    raw: EventQueue<Sample, RAW_INPUTS>,
    retained: Option<Sample>,
    button: Button,
    touch: Touch,
    buttons: EventQueue<ButtonEvent, INPUT_EVENTS>,
    touches: EventQueue<TouchEvent, INPUT_EVENTS>,
    touch_turn: bool,
    snapshot: Snapshot,
    damage: Damage,
    total_samples: u32,
    total_events: u32,
}
impl<B: Link> fmt::Debug for Services<B> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Services")
            .field("queued_input", &self.queued_inputs())
            .field("pending_tx", &self.pending.is_some())
            .field("tx_state", &self.tx_state)
            .finish_non_exhaustive()
    }
}
impl<B: Link> Services<B> {
    /// Owns the adapter and actual queues; input policy is supplied explicitly.
    /// `owner_generation` must never be reused for another coexisting or
    /// reconstructed Services owner in the same recovery domain. The caller
    /// allocates it; this example deliberately has no global identity allocator.
    pub fn new(
        owner_generation: NonZeroU64,
        link: B,
        button: ButtonConfig,
        touch: TouchConfig,
    ) -> Self {
        Self {
            link,
            target: None,
            verified: false,
            rx: WriteSlot::new(),
            pending: None,
            tx_state: TxState::Ready,
            next_token: 1,
            owner_generation,
            raw: EventQueue::new(),
            retained: None,
            button: Button::new(button),
            touch: Touch::new(touch),
            buttons: EventQueue::new(),
            touches: EventQueue::new(),
            touch_turn: false,
            snapshot: Snapshot::default(),
            damage: Damage::default(),
            total_samples: 0,
            total_events: 0,
        }
    }
    /// Inspect the external adapter without granting any UI mutation.
    pub const fn link(&self) -> &B {
        &self.link
    }
    /// Explicit adapter control/recovery between steps; adapters serialize ISR access.
    pub const fn link_mut(&mut self) -> &mut B {
        &mut self.link
    }
    /// Current visual snapshot, copied before a frame begins.
    pub const fn snapshot(&self) -> Snapshot {
        self.snapshot
    }
    /// Current admission state.
    pub const fn tx_state(&self) -> TxState {
        self.tx_state
    }
    /// Token of the single retained value, if any.
    pub fn pending_token(&self) -> Option<TxToken> {
        self.pending.as_ref().map(|p| p.token)
    }
    /// Actual total outstanding raw and recognized input items.
    pub fn queued_inputs(&self) -> usize {
        self.raw.len()
            + usize::from(self.retained.is_some())
            + self.buttons.len()
            + self.touches.len()
    }
    /// Successful raw samples, saturating at the integer limit.
    pub const fn processed_samples(&self) -> u32 {
        self.total_samples
    }
    /// Consumed recognized events, saturating at the integer limit.
    pub const fn processed_events(&self) -> u32 {
        self.total_events
    }
    /// Take next-frame damage; no current frame can observe mutable scene state.
    pub fn take_damage(&mut self) -> Damage {
        core::mem::take(&mut self.damage)
    }
    /// Accept one entire physical sample, preserving the source timestamp.
    /// # Errors
    /// Full leaves the caller responsible for retaining/retrying the same sample.
    pub fn enqueue_input(&mut self, sample: Sample) -> Result<(), EnqueueError> {
        self.raw.push(sample).map_err(|_| EnqueueError::Full)
    }
    /// Copy one complete caller-supplied value for the currently verified route.
    /// # Errors
    /// No overwrite on Full, `TooLong`, unavailable route or exhausted token owner.
    pub fn enqueue_notification(&mut self, value: &[u8]) -> Result<TxToken, EnqueueError> {
        if self.pending.is_some() {
            return Err(EnqueueError::Full);
        }
        if value.len() > VALUE_BYTES {
            return Err(EnqueueError::TooLong);
        }
        let target = self
            .target
            .filter(|_| self.verified)
            .ok_or(EnqueueError::NoTarget)?;
        let next = self
            .next_token
            .checked_add(1)
            .ok_or(EnqueueError::Exhausted)?;
        let token = TxToken {
            owner: self.owner_generation,
            sequence: self.next_token,
        };
        let mut bytes = [0; VALUE_BYTES];
        bytes[..value.len()].copy_from_slice(value);
        self.pending = Some(Pending {
            target,
            bytes,
            len: value.len(),
            token,
        });
        self.next_token = next;
        Ok(token)
    }
    /// Resolve only an exact uncertain token using actual adapter evidence.
    /// # Errors
    /// Stale tokens and wrong states cannot clear or resend another value.
    pub fn resolve(&mut self, token: TxToken, resolution: Resolution) -> Result<(), EnqueueError> {
        if self.tx_state != TxState::Uncertain(token) || self.pending_token() != Some(token) {
            return Err(EnqueueError::WrongToken);
        }
        if resolution == Resolution::Accepted {
            self.pending = None;
            self.snapshot.tx_active = !self.snapshot.tx_active;
            self.damage.tx = true;
        }
        self.tx_state = TxState::Ready;
        Ok(())
    }
    /// Explicitly retry a known-not-submitted backend configuration fault after repair.
    /// # Errors
    /// Only the exact currently faulted token is accepted.
    pub fn retry_after_repair(&mut self, token: TxToken) -> Result<(), EnqueueError> {
        if self.tx_state != TxState::Faulted(token) || self.pending_token() != Some(token) {
            return Err(EnqueueError::WrongToken);
        }
        self.tx_state = TxState::Ready;
        Ok(())
    }
    /// One bounded round; errors are recorded per lane and do not suppress input.
    pub fn round(&mut self, report: &mut ServiceReport<B::Error>) {
        report.rounds = report.rounds.saturating_add(1);
        report.polls = report.polls.saturating_add(1);
        self.verified = false;
        match self.link.poll() {
            Ok(target) => {
                self.verified = true;
                self.observe(target, report);
                self.receive(report);
                self.transmit(report);
            }
            Err(e) => first(&mut report.poll_error, e),
        }
        self.input(report);
        self.events(report);
    }
    fn observe(&mut self, target: Option<B::Target>, report: &mut ServiceReport<B::Error>) {
        if self.target == target {
            return;
        }
        if self.pending.take().is_some() {
            report.retired = report.retired.saturating_add(1);
        }
        if self.rx.clear().is_some() {
            report.stale_rx = report.stale_rx.saturating_add(1);
        }
        self.tx_state = TxState::Ready;
        self.target = target;
        self.snapshot.connected = target.is_some();
        self.damage.full = true;
    }
    fn receive(&mut self, report: &mut ServiceReport<B::Error>) {
        if self.target.is_none() {
            return;
        }
        if let Err(e) = self.link.receive(&mut self.rx) {
            first(&mut report.receive_error, e);
        }
        if let Some((meta, _)) = self.rx.peek() {
            if Some(meta.target) == self.target {
                self.snapshot.rx_active = !self.snapshot.rx_active;
                self.damage.rx = true;
                report.received = report.received.saturating_add(1);
            } else {
                report.stale_rx = report.stale_rx.saturating_add(1);
            }
            self.rx.clear();
        }
    }
    fn transmit(&mut self, report: &mut ServiceReport<B::Error>) {
        if self.tx_state != TxState::Ready {
            return;
        }
        let Some(p) = self.pending.as_ref() else {
            return;
        };
        report.attempts = report.attempts.saturating_add(1);
        let result = CheckedNotifier::new(NotificationRef::new(&mut self.link))
            .try_notify(p.target, &p.bytes[..p.len]);
        match result {
            Ok(_) => {
                self.pending = None;
                self.snapshot.tx_active = !self.snapshot.tx_active;
                self.damage.tx = true;
                report.accepted = report.accepted.saturating_add(1);
            }
            Err(e) => {
                match &e {
                    NotifyError::Backend(raw) if !self.link.definitely_not_queued(raw) => {
                        self.tx_state = TxState::Uncertain(p.token);
                    }
                    NotifyError::InvalidCapacity { .. } => {
                        self.tx_state = TxState::Faulted(p.token);
                    }
                    _ => {}
                }
                first(&mut report.notify_error, e);
            }
        }
    }
    fn input(&mut self, report: &mut ServiceReport<B::Error>) {
        if self.retained.is_none() {
            self.retained = self.raw.pop();
        }
        let Some(sample) = self.retained else {
            return;
        };
        let result = match sample {
            Sample::Button { pressed, at_us } => {
                self.button.sample(pressed, at_us, &mut self.buttons)
            }
            Sample::Touch { sample, at_us } => self.touch.update(sample, at_us, &mut self.touches),
            Sample::TouchTick(at_us) => self.touch.tick(at_us, &mut self.touches),
        };
        match result {
            Ok(()) => {
                self.retained = None;
                report.samples = report.samples.saturating_add(1);
                self.total_samples = self.total_samples.saturating_add(1);
            }
            Err(e) => {
                if e != InputError::Full {
                    self.retained = None;
                    report.rejected = report.rejected.saturating_add(1);
                }
                first(&mut report.input_error, e);
            }
        }
    }
    fn events(&mut self, report: &mut ServiceReport<B::Error>) {
        let mut delta = 0u8;
        let mut reset = false;
        let consumed = if self.touch_turn {
            self.touches
                .pop()
                .map(|e| match e {
                    TouchEvent::Tap(_) | TouchEvent::Swipe(Direction::Right | Direction::Down) => {
                        delta = 1;
                    }
                    TouchEvent::Swipe(Direction::Left | Direction::Up) => delta = 3,
                    TouchEvent::Held(_) => reset = true,
                    _ => {}
                })
                .is_some()
        } else {
            self.buttons
                .pop()
                .map(|e| {
                    if e == ButtonEvent::Pressed {
                        delta = 1;
                    }
                })
                .is_some()
        };
        self.touch_turn = !self.touch_turn;
        if consumed {
            report.events = report.events.saturating_add(1);
            self.total_events = self.total_events.saturating_add(1);
        }
        let selected = if reset {
            0
        } else {
            (self.snapshot.selection + delta) % 4
        };
        if selected != self.snapshot.selection {
            self.snapshot.selection = selected;
            self.damage.full = true;
        }
    }
}
