//! Real history wire handler over paged log plus `AtomicSnapshot` metadata.
#![allow(clippy::unwrap_used, clippy::expect_used)]
mod paged_service_support;
use core::num::NonZeroU64;
use device_history_service::{HistoryFailure, HistoryHandler, RecordStore};
use device_protocol::{
    DataKind, Frame, Header, HistoryFilter, HistoryRecord, HistoryRequest, Kind, ModuleEntry,
    SharedDataLane,
};
use device_services::{ServiceHandler, SessionError};
use paged_service_support::*;

type Handler<'a, S> = HistoryHandler<'a, S, 1, 16>;
fn handler<'a, S: RecordStore>(store: &'a mut S, lane: &'a SharedDataLane) -> Handler<'a, S> {
    HistoryHandler::new(
        ModuleEntry {
            module: 0x10,
            major: 1,
            minor: 2,
            availability: 1,
            features: 0,
            input_max: 512,
            output_max: 512,
        },
        store,
        &Access,
        lane,
        128,
        true,
    )
    .unwrap()
}
fn data_lane(id: u64) -> SharedDataLane {
    SharedDataLane::new(NonZeroU64::new(id).unwrap())
}
fn encoded(request: HistoryRequest) -> Vec<u8> {
    let mut bytes = [0; 128];
    let length = request.encode(&mut bytes).unwrap();
    bytes[..length].to_vec()
}
fn frame(request: HistoryRequest, bytes: &[u8]) -> Frame<'_> {
    Frame {
        header: Header {
            kind: Kind::Request,
            module: 0x10,
            opcode: request.opcode(),
            message_id: 1,
            offset: 0,
            total_length: u16::try_from(bytes.len()).unwrap(),
        },
        payload: bytes,
    }
}
fn run<S: RecordStore>(service: &mut Handler<'_, S>, request: HistoryRequest) -> Vec<u8> {
    let bytes = encoded(request);
    let mut out = [0; 512];
    let length = service.dispatch(frame(request, &bytes), &mut out).unwrap();
    out[..length].to_vec()
}
fn open<S: RecordStore>(service: &mut Handler<'_, S>) {
    assert_eq!(&run(service, HistoryRequest::Open(filter()))[..4], &[0; 4]);
}
fn ack(upto_id: u64) -> HistoryRequest {
    HistoryRequest::Ack {
        snapshot: 1,
        epoch: 3,
        upto_id,
    }
}
fn read<S: RecordStore>(service: &mut Handler<'_, S>, after_id: u64, max_records: u16) -> u16 {
    let request = HistoryRequest::Read {
        snapshot: 1,
        after_id,
        max_records,
    };
    let response = run(service, request);
    assert_eq!(&response[..4], &[0; 4]);
    let stream = u16::from_le_bytes(response[4..6].try_into().unwrap());
    service
        .response_admitted(frame(request, &encoded(request)), &response)
        .unwrap();
    stream
}
fn admit_one<S: RecordStore>(service: &mut Handler<'_, S>, after: u64) {
    let stream = read(service, after, 1);
    service.grant(DataKind::History, stream, 1).unwrap();
    let event = service.next_data(&mut [0; 128]).unwrap().unwrap();
    service.finish_data(event.message_id).unwrap();
    assert!(service.next_data(&mut [0; 128]).unwrap().is_none());
    assert!(service.done(&mut [0; 64]).unwrap().is_some());
    service.done_admitted(stream).unwrap();
}

// Catches granting admission for READ, generated bytes, retries, or a wrong MID.
#[test]
fn test_should_gate_durable_wire_ack_on_exact_final_fragment_admission() {
    let control = MediumControl::blank();
    let mut media = control.media();
    let mut store = initialize(&mut media, Clock::new());
    for value in [60, 61] {
        store.append(input(&[value, 0, 0, 1])).unwrap();
    }
    let lane = data_lane(1);
    {
        let mut service = handler(&mut store, &lane);
        open(&mut service);
        let request = HistoryRequest::Read {
            snapshot: 1,
            after_id: 0,
            max_records: 2,
        };
        let response = run(&mut service, request);
        let stream = u16::from_le_bytes(response[4..6].try_into().unwrap());
        assert_eq!(service.next_data(&mut [0; 128]), Ok(None));
        let mut bad = response.clone();
        bad[4] ^= 1;
        assert!(
            service
                .response_admitted(frame(request, &encoded(request)), &bad)
                .is_err()
        );
        service
            .response_admitted(frame(request, &encoded(request)), &response)
            .unwrap();
        assert_eq!(service.next_data(&mut [0; 128]), Ok(None));
        service.grant(DataKind::History, stream, 2).unwrap();
        let mut bytes = [0; 128];
        let first = service.next_data(&mut bytes).unwrap().unwrap();
        let saved = bytes;
        assert_eq!(service.next_data(&mut bytes), Ok(Some(first)));
        assert_eq!(bytes, saved);
        assert_eq!(
            service.finish_data(first.message_id + 1),
            Err(HistoryFailure::Identity)
        );
        assert_eq!(run(&mut service, ack(1)), [4, 0, 0, 0]);
        service.finish_data(first.message_id).unwrap();
        assert_eq!(run(&mut service, ack(2)), [4, 0, 0, 0]);
        let second = service.next_data(&mut bytes).unwrap().unwrap();
        let record = HistoryRecord::decode(&bytes[..second.length], 128).unwrap();
        assert_eq!(record.payload, &[61, 0, 0, 1]);
        assert_eq!(record.record_id, 2);
        service.finish_data(second.message_id).unwrap();
        assert_eq!(
            run(&mut service, ack(2)),
            [0, 0, 0, 0, 2, 0, 0, 0, 0, 0, 0, 0]
        );
        service.connection_closed().unwrap();
    }
    assert_eq!(lane.available(), Ok(false));
    store.recover().unwrap();
    let lease = store.open(42, filter(), 0, &Access).unwrap();
    assert_eq!(lease.committed_id, 2);
}

// Catches treating a late READ cursor as cumulative coverage or losing late bits.
#[test]
fn test_should_fill_early_prefix_after_late_wire_query_without_losing_late_proof() {
    let control = MediumControl::blank();
    let mut media = control.media();
    let mut store = initialize(&mut media, Clock::new());
    for value in [60, 61, 62] {
        store.append(input(&[value, 0, 0, 1])).unwrap();
    }
    let lane = data_lane(2);
    let mut service = handler(&mut store, &lane);
    open(&mut service);
    admit_one(&mut service, 2);
    assert_eq!(run(&mut service, ack(3)), [4, 0, 0, 0]);
    admit_one(&mut service, 0);
    assert_eq!(run(&mut service, ack(3)), [4, 0, 0, 0]);
    admit_one(&mut service, 1);
    assert_eq!(
        run(&mut service, ack(3)),
        [0, 0, 0, 0, 3, 0, 0, 0, 0, 0, 0, 0]
    );
    service.connection_closed().unwrap();
}

// Catches forgotten durable ACK or recreated proof after a new owner/actor.
#[test]
fn test_should_resume_new_wire_actor_above_durable_ack_after_restart() {
    let control = MediumControl::blank();
    let clock = Clock::new();
    {
        let mut media = control.media();
        let mut store = initialize(&mut media, clock.clone());
        for value in [60, 61, 62] {
            store.append(input(&[value, 0, 0, 1])).unwrap();
        }
        let lane = data_lane(3);
        let mut service = handler(&mut store, &lane);
        open(&mut service);
        admit_one(&mut service, 0);
        assert_eq!(&run(&mut service, ack(1))[..4], &[0; 4]);
        service.connection_closed().unwrap();
    }
    let mut media = control.media();
    let mut store = reopen(&mut media, clock);
    let writes = control.writes.get();
    let lane = data_lane(4);
    {
        let mut service = handler(&mut store, &lane);
        open(&mut service);
        assert_eq!(&run(&mut service, ack(1))[..4], &[0; 4]);
        assert_eq!(control.writes.get(), writes);
        admit_one(&mut service, 2);
        assert_eq!(run(&mut service, ack(3)), [4, 0, 0, 0]);
        admit_one(&mut service, 1);
        assert_eq!(&run(&mut service, ack(3))[..4], &[0; 4]);
        service.connection_closed().unwrap();
    }
    assert_eq!(store.count(filter(), &Access).unwrap(), (3, 3));
}

// Catches pretending an uncertain ACK failed cleanly or retaining old proof.
#[test]
fn test_should_poison_uncertain_wire_ack_and_rebuild_actor_after_recovery() {
    for barrier in 1..=3 {
        let control = MediumControl::blank();
        let mut media = control.media();
        let mut store = initialize(&mut media, Clock::new());
        store.append(input(&[60, 0, 0, 1])).unwrap();
        let lane = data_lane(10 + u64::from(barrier));
        {
            let mut service = handler(&mut store, &lane);
            open(&mut service);
            admit_one(&mut service, 0);
            control.fail_sync.set(Some(control.syncs.get() + barrier));
            let request = ack(1);
            assert_eq!(
                service.dispatch(frame(request, &encoded(request)), &mut [0; 128]),
                Err(SessionError::AuthorizationRevoked)
            );
            assert_eq!(
                service.next_data(&mut [0; 128]),
                Err(HistoryFailure::Closed)
            );
            assert!(service.connection_closed().is_err());
        }
        assert!(store.directory().is_err());
        store.recover().unwrap();
        let fresh = store.open(7, filter(), 0, &Access).unwrap();
        assert!(fresh.committed_id <= 1);
        if fresh.committed_id == 0 {
            assert_eq!(
                store.ack_atomic(fresh, filter(), 3, 1, 0, &Access),
                Err(HistoryFailure::InvalidState)
            );
        }
        store.close(fresh).unwrap();
        let lane = data_lane(20 + u64::from(barrier));
        let mut service = handler(&mut store, &lane);
        open(&mut service);
        admit_one(&mut service, 0);
        assert_eq!(&run(&mut service, ack(1))[..4], &[0; 4]);
        service.connection_closed().unwrap();
    }
}

// Catches accepting an all-matching filtered query as ACK authority.
#[test]
fn test_should_keep_filtered_wire_query_read_only_and_check_snapshot_first() {
    let control = MediumControl::blank();
    let clock = Clock::new();
    let mut media = control.media();
    let mut store = initialize(&mut media, clock.clone());
    for value in [60, 61, 62] {
        store.append(input(&[value, 0, 0, 1])).unwrap();
    }
    let lane = data_lane(30);
    {
        let mut service = handler(&mut store, &lane);
        let filter = HistoryFilter {
            filter_flags: 2,
            record_type: 0x20,
            ..filter()
        };
        assert_eq!(
            &run(&mut service, HistoryRequest::OpenV2(filter))[..4],
            &[0; 4]
        );
        admit_one(&mut service, 2);
        assert_eq!(run(&mut service, ack(3)), [4, 0, 5, 255]);
        assert_ne!(
            run(
                &mut service,
                HistoryRequest::Ack {
                    snapshot: 99,
                    epoch: 3,
                    upto_id: 3
                }
            ),
            [4, 0, 5, 255]
        );
        clock.set(60_000);
        service.advance(60_000).unwrap();
        assert_ne!(run(&mut service, ack(3)), [4, 0, 5, 255]);
        service.connection_closed().unwrap();
    }
    let lease = store.open(4, filter(), 60_000, &Access).unwrap();
    assert_eq!(lease.committed_id, 0);
}

// Catches cancel/close implicitly ACKing and changing an in-flight retry.
#[test]
fn test_should_drain_cancel_keep_exact_data_and_close_without_advancing_ack() {
    let control = MediumControl::blank();
    let mut media = control.media();
    let mut store = initialize(&mut media, Clock::new());
    store.append(input(&[60, 0, 0, 1])).unwrap();
    let lane = data_lane(40);
    {
        let mut service = handler(&mut store, &lane);
        open(&mut service);
        let stream = read(&mut service, 0, 1);
        service.grant(DataKind::History, stream, 1).unwrap();
        let mut bytes = [0; 128];
        let event = service.next_data(&mut bytes).unwrap().unwrap();
        let saved = bytes;
        let cancel = HistoryRequest::CancelRead {
            snapshot: 1,
            stream_id: stream,
        };
        let input = encoded(cancel);
        assert_eq!(service.response_ready(frame(cancel, &input)), Ok(false));
        assert_eq!(
            service.dispatch(frame(cancel, &input), &mut [0; 128]),
            Err(SessionError::Deferred)
        );
        assert_eq!(lane.available(), Ok(false));
        assert_eq!(service.next_data(&mut bytes), Ok(Some(event)));
        assert_eq!(bytes, saved);
        service.finish_data(event.message_id).unwrap();
        assert_eq!(service.response_ready(frame(cancel, &input)), Ok(true));
        assert_eq!(
            run(&mut service, cancel),
            [
                0,
                0,
                0,
                0,
                event.message_id.to_le_bytes()[0],
                event.message_id.to_le_bytes()[1]
            ]
        );
        assert_eq!(lane.available(), Ok(true));
        let next = read(&mut service, 0, 1);
        assert_ne!(next, stream);
        assert_eq!(
            run(&mut service, HistoryRequest::Close { snapshot: 1 }),
            [0; 6]
        );
        assert_eq!(service.next_data(&mut bytes), Ok(None));
        service.connection_closed().unwrap();
    }
    let lease = store.open(2, filter(), 0, &Access).unwrap();
    assert_eq!(lease.committed_id, 0);
    assert_eq!(
        store.ack_atomic(lease, filter(), 3, 1, 0, &Access),
        Err(HistoryFailure::InvalidState)
    );
}

#[path = "paged_service_support/producer.rs"]
mod producer;
// Catches masking a real producer directory update to keep an old actor alive.
#[test]
fn test_should_end_old_actor_when_real_producer_append_changes_directory_and_rebuild() {
    let control = MediumControl::blank();
    let mut media = control.media();
    let mut store = initialize(&mut media, Clock::new());
    store.append(input(&[60, 0, 0, 1])).unwrap();
    let mut producer = producer::ProducerOnAdmission {
        store,
        append_once: true,
    };
    let lane = data_lane(50);
    {
        let mut service = handler(&mut producer, &lane);
        open(&mut service);
        let stream = read(&mut service, 0, 1);
        service.grant(DataKind::History, stream, 1).unwrap();
        let event = service.next_data(&mut [0; 128]).unwrap().unwrap();
        assert_eq!(
            service.finish_data(event.message_id),
            Err(HistoryFailure::CursorExpired)
        );
        assert!(service.must_end_session());
        assert_eq!(
            service.next_data(&mut [0; 128]),
            Err(HistoryFailure::Closed)
        );
        service.connection_closed().unwrap();
    }
    assert_eq!(producer.store.directory().unwrap().domains[0].newest_id, 2);
    let fresh_lane = data_lane(51);
    {
        let mut service = handler(&mut producer, &fresh_lane);
        open(&mut service);
        assert_eq!(run(&mut service, ack(1)), [4, 0, 0, 0]);
        admit_one(&mut service, 0);
        admit_one(&mut service, 1);
        assert_eq!(&run(&mut service, ack(2))[..4], &[0; 4]);
        service.connection_closed().unwrap();
    }
}
